def get_initials(names: str, div: str = " ") -> str:
    """Get first letter of word (upto 5) to make an id"""
    all = names.split(div)
    initials = ""
    count = 0
    for n in all:
        count = count + 1
        if len(n) > 0 and n[0].isalpha():
            initials = f"{initials}{n[0]}"
        if count > 5:
            break
    return initials


def write_yaml(name: str, values: Any) -> None:
    """Write given dat to  the file name  YAML"""
    with open(name, "w") as file:
        file.write(f"# this file` was generated by {script_name} do not edit\n")
        yaml.dump(values, file)


def write_model(name: str, authors: dict[str, AuthorDbAuthor]) -> None:
    """Write given data to  the file name  YAML"""
    adb = AuthorYaml(authors=authors)
    with open(name, "w") as file:
        yaml.dump(adb.model_dump(), file)


def write_affil(name: str, affils: dict[str, Affiliation]) -> None:
    """Write given data to  the file name  YAML"""
    adb = AffilYaml(affiliations=affils)
    with open(name, "w") as file:
        yaml.dump(adb.model_dump(), file)


def load_model(filename: str) -> dict[str, AuthorDbAuthor]:
    """Read authors  data from the YAML file"""
    with open(filename) as file:
        yaml_data = yaml.safe_load(file)
        print("Parsing into AuthorYaml object...\n")
        adb = AuthorYaml.model_validate(yaml_data)
    return adb.authors


def placeholder_affil(
    domain: str,
    affils: dict[str, Affiliation],
    newaffils: dict[str, Affiliation],
) -> str:
    """Return the id of an email-only placeholder affiliation for domain,
    creating it in newaffils if needed.

    The id is the first part of the domain, capitalized. If that id is
    already taken by an affiliation with a different domain a numeric
    suffix is added rather than pointing the email at the wrong domain.
    """
    domain = domain.lower()
    base = domain.split(".")[0].capitalize()
    daffil = base
    n = 2
    while True:
        existing = newaffils.get(daffil) or affils.get(daffil)
        if existing is None:
            break
        if existing.email and existing.email.lower() == domain:
            return daffil
        daffil = f"{base}{n}"
        n += 1
    newaffils[daffil] = Affiliation(
        institute=f"Email only for {domain}",
        address=None,
        email=domain,
    )
    print(f"  Created placeholder affiliation '{daffil}' for domain '{domain}'")
    return daffil


def handle_email(
    email: str,
    affils: dict[str, Affiliation],
    affilid: str | None,
    newaffils: dict[str, Affiliation],
) -> str:
    """Return local-part or local-part@affilid for email.

    1. If the author's affiliation has this domain, return just the local-part.
    2. If any other affiliation has it, encode as local-part@thataffilid.
    3. If the author's affiliation has no domain yet, stage a copy of it with
       this domain in newaffils.
    4. Otherwise use (or create) an email-only placeholder affiliation.

    Affiliations already staged in newaffils take precedence over affils.
    affils is never modified.
    """
    if "@" not in email:
        return email

    mailid, domain = email.split("@", 1)
    domain = domain.lower()
    known = {**affils, **newaffils}

    def has_domain(a: Affiliation) -> bool:
        return a.email is not None and a.email.lower() == domain

    # 1) The author's own affiliation has this domain.
    if affilid in known and has_domain(known[affilid]):
        return mailid

    # 2) Some other affiliation owns this domain.
    for aid, a in known.items():
        if has_domain(a):
            return f"{mailid}@{aid}"

    # 3) The author's affiliation has no domain yet - give it this one.
    if affilid in known and (not known[affilid].email or known[affilid].email == "null"):
        newaffils[affilid] = known[affilid].model_copy(update={"email": domain})
        print(f"  Adding email domain '{domain}' to affiliation '{affilid}'")
        return mailid

    # 4) New domain - use a placeholder affiliation for it.
    return f"{mailid}@{placeholder_affil(domain, affils, newaffils)}"


def lower_strip_utf(s: str) -> str:
    """Lower case, strip utf chars and other chars and space"""
    id = strip_utf(s)  # no utf
    id = id.lower().replace(" ", "")
    return id


def make_id(name: str, surname: str) -> str:
    """Make id form surnameinitials no space lowecase"""
    initials = get_initials(name)
    id = lower_strip_utf(f"{surname}{initials}")  # last name initial
    return id


def parse_affiliation(affil_str: str) -> Affiliation:
    """Parse an affiliation string into an Affiliation object."""
    parts = [p.strip() for p in affil_str.split(",")]
    if len(parts) < 2:
        raise ValueError("Affiliation string does not have enough parts")
    name = parts[0]
    address_str = unicode_to_latex(", ".join(parts[1:]))
    # Try to extract country (last part)
    country = parts[-1]
    # Try to extract postal code (look for 5-digit number)
    postal_code_match = re.search(r"\b\d{5}\b", address_str)
    postal_code = postal_code_match.group(0) if postal_code_match else ""
    # The rest is street and city
    street_and_city = address_str.replace(country, "").replace(postal_code, "").strip(", ")
    address = Address(
        example_expanded=unicode_to_latex(affil_str),
        street=street_and_city,
        city="",  # Optionally parse city if possible
        postcode=postal_code,
        country_code=country,
    )
    return Affiliation(institute=unicode_to_latex(name), address=address)


def process_affiliations(
    row: list[Any],
    idx: int,
    affils: dict[str, Affiliation],
    newaffils: dict[str, Affiliation],
    missing_affils: list[str],
) -> list[str]:
    """
    Process the AFFIL column from a row and update affiliations.

    Parameters
    ----------
    row : list
        A row of data from the Google Sheet.
    idx : int
        Row index (for logging).
    affils : dict[str, Affiliation]
        Known affiliations (global database).
    newaffils : dict[str, Affiliation]
        Newly discovered affiliations (staged).
    missing_affils : list[str]
        List to append missing affiliation IDs.

    Returns
    -------
    affilids : list[str]
        List of affiliation IDs found/created for this row.
    """
    affilids = []

    if len(row) > AFFIL and len(row[AFFIL]) > 0:
        affilidForm = str(row[AFFIL]).strip().split("/")

        if affilidForm[0] == "AURA":
            # Chilean quirk: AURA/Rubin gets normalized
            affilidForm[0] = "RubinObsC"

        for affilid in affilidForm:
            affilid = affilid.strip()
            if affilid not in affils:
                if len(affilid) < 10:
                    print(f"Affiliation does not exist: {affilid} - skipping {id} at index {idx}")
                    missing_affils.append(affilid)
                else:  # assume it's a new affiliation string
                    affil = affilid
                    if "rubin" in affil.lower():
                        affilid = "RubinObsC"
                    else:
                        affilid = get_initials(affil)
                        try:
                            newaffils[affilid] = parse_affiliation(affil)
                            affils[affilid] = newaffils[affilid]
                        except Exception:
                            print(f"Affiliation parse failed: {affilid} - skipping {id} at index {idx}")
                            missing_affils.append(affilid)
            affilids.append(affilid)

        if affilids and affilids[0] not in affils:
            return []  # skip this row, primary affiliation missing

    return affilids


def genFilesPartial(
    values: list, skip: int, cols: dict[str, int] | None = None, skip_file: str | None = None
) -> int:
    """Partial update mode: looks up existing authors by ID and only updates
    fields that are provided (non-empty) in the sheet. Does not clobber
    existing values with empty ones.

    Parameters
    ----------
    values : list
        Rows from the Google Sheet.
    skip : int
        Number of rows to skip.
    cols : dict[str, int] | None
        Override column indices for partial mode.
        Keys: AUTHORID, EMAIL, SURNAME, NAME, AFFIL, ORCID.
        If None, uses global defaults.

    Returns number of issues found.
    """
    # Use provided column map or fall back to globals
    col_authorid = cols.get("AUTHORID", AUTHORID) if cols else AUTHORID
    col_email = cols.get("EMAIL", EMAIL) if cols else EMAIL
    col_surname = cols.get("SURNAME", SURNAME) if cols else SURNAME
    col_name = cols.get("NAME", NAME) if cols else NAME
    col_affil = cols.get("AFFIL", AFFIL) if cols else AFFIL
    col_orcid = cols.get("ORCID", ORCID) if cols else ORCID

    print(
        f"Column mapping: AUTHORID={col_authorid}, EMAIL={col_email}, "
        f"SURNAME={col_surname}, NAME={col_name}, AFFIL={col_affil}, ORCID={col_orcid}"
    )
    if not values:
        print("No data found.")
        return 0

    updated_authors: dict[str, AuthorDbAuthor] = {}
    newaffils: dict[str, Affiliation] = {}
    authordb = load_authordb()
    authors = authordb.authors
    affils = authordb.affiliations
    missing_affils: list[str] = []
    notfound: list[str] = []
    updated: list[str] = []

    for idx, row in enumerate(values):
        if idx < skip:
            continue

        # Get author ID - required
        if len(row) <= col_authorid:
            print(f"Row {idx}: no authorid column")
            continue
        aid = str(row[col_authorid]).strip().replace(" ", "").lower()
        if not aid:
            print(f"Row {idx}: empty authorid")
            continue

        if aid not in authors:
            print(f"Row {idx}: author '{aid}' not found in authordb")
            notfound.append(aid)
            continue

        # Start with existing author record
        existing = authors[aid]
        new_email = existing.email
        new_family = existing.family_name
        new_given = existing.given_name
        new_orcid = existing.orcid
        new_affil = existing.affil
        new_altaffil = existing.altaffil

        changed = False

        # Update email if provided
        if len(row) > col_email and row[col_email] and str(row[col_email]).strip():
            raw_email = str(row[col_email]).strip()
            # Check existing domains first, then add if needed
            new_email = handle_email(raw_email, affils, new_affil[0] if new_affil else None, newaffils)
            if new_email != existing.email:
                print(f"Row {idx}: {aid} email: '{existing.email}' -> '{new_email}'")
                changed = True

        # Update surname if provided
        if len(row) > col_surname and row[col_surname] and str(row[col_surname]).strip():
            new_family = unicode_to_latex(str(row[col_surname]).strip())
            if new_family != existing.family_name:
                print(f"Row {idx}: {aid} family_name: '{existing.family_name}' -> '{new_family}'")
                changed = True

        # Update given name if provided
        if len(row) > col_name and row[col_name] and str(row[col_name]).strip():
            new_given = unicode_to_latex(str(row[col_name]).strip())
            if new_given != existing.given_name:
                print(f"Row {idx}: {aid} given_name: '{existing.given_name}' -> '{new_given}'")
                changed = True

        # Update ORCID if provided
        if len(row) > col_orcid and row[col_orcid] and str(row[col_orcid]).strip():
            orc = str(row[col_orcid]).strip().replace("https://orcid.org/", "")
            if len(orc) >= 2:
                new_orcid = orc
                if new_orcid != existing.orcid:
                    print(f"Row {idx}: {aid} orcid: '{existing.orcid}' -> '{new_orcid}'")
                    changed = True

        # Update affiliation if provided
        if len(row) > col_affil and row[col_affil] and str(row[col_affil]).strip():
            # Handle affiliations directly (process_affiliations uses globals)
            affilids = [a.strip() for a in str(row[col_affil]).strip().split("/")]
            valid_affilids = []
            for affilid in affilids:
                if affilid in affils:
                    valid_affilids.append(affilid)
                else:
                    print(f"Row {idx}: unknown affiliation '{affilid}'")
                    missing_affils.append(affilid)
            if valid_affilids and valid_affilids != existing.affil:
                new_affil = valid_affilids
                print(f"Row {idx}: {aid} affil: {existing.affil} -> {new_affil}")
                changed = True

        if changed:
            updated_authors[aid] = AuthorDbAuthor(
                given_name=new_given,
                family_name=new_family,
                orcid=new_orcid,
                email=new_email,
                affil=new_affil,
                altaffil=new_altaffil,
            )
            updated.append(aid)

    print(
        "\n"
        f"Partial update summary:\n"
        f"  Processed: {idx + 1} rows (skipped first {skip})\n"
        f"  Updated: {len(updated)} authors\n"
        f"  Not found: {len(notfound)} ({', '.join(notfound)})\n"
        f"  Missing affiliations: {len(missing_affils)} ({', '.join(missing_affils)})\n"
        f"  New affiliations/domains: {len(newaffils)}\n"
    )

    if skip_file:
        with open(skip_file, "w") as f:
            f.write(f"{idx + 1}\n")

    write_model("new_authors.yaml", updated_authors)
    if newaffils:
        write_affil("new_affiliations.yaml", newaffils)

    return len(notfound) + len(missing_affils)


def genFilesADB(values: list, skip: int, skip_file: str = "skip") -> int:
    """Assumes we are procsssing the AuthordDB update form.
    It will produce:
        new_authors.yaml - authors that need to be created/updated.
        new_affiliations.yaml - new affilliations inc new emails
        No authors.yaml

    values contains the selected cells from a google sheet with format
    with cells mapping set up in the start of the routine but contains
    Email Address
    Affirmation
    authorid (May be blank)
    surname (aka family name or last name)
    First names,
    affilid
    ORCID (optional)
    """
    if not values:
        print("No data found.")
    else:
        clash = []
        check: list[str] = []
        bad = []
        toupdate = []
        notfound = []
        newauthors: dict[str, AuthorDbAuthor] = {}
        newaffils: dict[str, Affiliation] = {}
        authordb = load_authordb()
        authors = authordb.authors
        affils = authordb.affiliations
        missing_affils: list[str] = []  #  for missing affiliations

        for idx, row in enumerate(values):
            id = str(row[AUTHORID]).replace(" ", "")
            newid = len(id) == 0 or id.upper() == "NEW" or id.upper() == "NUEVO"
            if idx < skip:
                if id not in authors:
                    print(f"Skipping author {id} - but that author was not found in authordb")
                continue  # Skip this for update/new

            if newid:
                id = make_id(row[NAME], row[SURNAME])
                if id in authors and idx >= skip:
                    print(f"Perhaps check  clash - author {id} - {row[AUTHORID]}, @{idx} ")
                    clash.append(id)
                elif idx >= skip:
                    print(f"New author {id} - {row[NAME]}, {row[SURNAME]} ")
            else:
                print(f"Update author {id} at index {idx} ")
                if id not in authors:
                    print(f"      but  author {id} - NOT FOUND ")
                    notfound.append(id)
                toupdate.append(id)
            # we have an id or a new id now check it
            if len(row) >= SURNAME:
                # some people put their full name in surname .
                snames = row[SURNAME].split(" ")
                if "," in row[SURNAME] or len(snames) >= 3:  # highly suspect
                    print(f"Check Surname for {id} at  {idx} - {row[SURNAME]}")
                    check.append(id)
            if len(row) >= SURNAME and not id.startswith(lower_strip_utf(row[SURNAME])) and id not in authors:
                # this can be a foreign charecter
                pid = make_id(row[NAME], row[SURNAME])
                print(f"Check  - author provided {id}  at {idx}- might {pid} - {row[SURNAME]}")
                bad.append(id)
            elif not re.match("^[a-z]+$", id):
                bad.append(id)
                print(f"Check - author id {id} at index {idx}: id is not all lowercase")

            # update or new - get the other fields

            if len(row) > AFFIL and len(row[AFFIL]) > 0:
                affilids = process_affiliations(row, idx, affils, newaffils, missing_affils)
                if len(row) > ORCID:
                    orc = str(row[ORCID]).strip().replace("https://orcid.org/", "")
                    if len(orc) < 2:
                        orcid = None
                    else:
                        orcid = orc
                else:
                    orcid = None
                email: str = handle_email(row[EMAIL], affils, affilids[0], newaffils)
                if id in authors and not newid:
                    oauthor = authors[id]
                    if orcid is None:  # dont clobber
                        orcid = oauthor.orcid
                author: AuthorDbAuthor = AuthorDbAuthor(
                    given_name=unicode_to_latex(row[NAME].strip()),
                    family_name=unicode_to_latex(row[SURNAME].strip()),
                    orcid=orcid,
                    email=email,
                    affil=affilids,
                    altaffil=[],
                )
                newauthors[id] = author
        print(
            "\n"
            f" Clash: {', '.join(clash)} \n"
            f" Not FOUND: {', '.join(notfound)} \n"
            f" Missing Affils: {', '.join(missing_affils)} \n"
            f" Check the ids: {', '.join(check)} \n"
            f"{len(newauthors) - len(toupdate)} new  and {len(toupdate)} to update, author entries.\n"
            f"{len(newaffils)} new affiliations (inc. any email domains) \n"
            f"{len(clash)} author entries need to be checked (see above) \n"
            f"{len(notfound)} author updates where authorid not found (see above) \n"
            f" Saw: {idx + 1} rows - skip file contains the number for reprocessing \n"
        )
        exitval = len(missing_affils) + len(check) + len(notfound) + len(clash)
        with open(skip_file, "w") as f:
            f.write(f"{idx + 1}\n")

        write_model("new_authors.yaml", newauthors)
        write_affil("new_affiliations.yaml", newaffils)

    return exitval


